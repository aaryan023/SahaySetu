-- SahaySetu citizen/admin feature schema additions.
-- Run once in the Supabase SQL editor before deploying the feature bundle.

alter table public.reports add column if not exists is_verified boolean not null default false;
alter table public.reports add column if not exists downvotes integer not null default 0;
alter table public.reports add column if not exists assigned_to text;
alter table public.reports add column if not exists resolution_note text;

do $$ begin
  if not exists (select 1 from pg_proc where proname='increment_upvotes' and pronamespace='public'::regnamespace) then
    execute $fn$create function public.increment_upvotes(row_id text) returns integer language sql security definer set search_path=public as 'update public.reports set upvotes=coalesce(upvotes,0)+1 where id::text=$1 returning upvotes'$fn$;
  end if;
  if not exists (select 1 from pg_proc where proname='increment_downvotes' and pronamespace='public'::regnamespace) then
    execute $fn$create function public.increment_downvotes(row_id text) returns integer language sql security definer set search_path=public as 'update public.reports set downvotes=coalesce(downvotes,0)+1 where id::text=$1 returning downvotes'$fn$;
  end if;
end $$;
grant execute on function public.increment_upvotes(text) to anon, authenticated;
grant execute on function public.increment_downvotes(text) to anon, authenticated;
revoke update on public.reports from anon, public;
grant update (upvotes, downvotes) on public.reports to anon, authenticated;

do $$ begin
  if not exists (select 1 from pg_policies where schemaname='public' and tablename='reports' and policyname='Public vote count update') then
    create policy "Public vote count update" on public.reports for update to anon, authenticated using (true) with check (true);
  end if;
end $$;

create table if not exists public.report_comments (
  id bigint generated by default as identity primary key,
  report_id text not null,
  name text not null,
  comment text not null,
  is_admin_reply boolean not null default false,
  created_at timestamptz not null default now()
);
create index if not exists report_comments_report_created_idx on public.report_comments(report_id,created_at);
grant select,insert on public.report_comments to anon;
grant all on public.report_comments to authenticated;
grant usage,select on sequence public.report_comments_id_seq to anon,authenticated;
alter table public.report_comments enable row level security;
drop policy if exists "Public read report comments" on public.report_comments;
create policy "Public read report comments" on public.report_comments for select to anon,authenticated using (true);
drop policy if exists "Public post citizen comments" on public.report_comments;
create policy "Public post citizen comments" on public.report_comments for insert to anon with check (is_admin_reply=false);
drop policy if exists "Authenticated comment moderation" on public.report_comments;
create policy "Authenticated comment moderation" on public.report_comments for all to authenticated using (true) with check (true);

create table if not exists public.volunteers (
  id bigint generated by default as identity primary key,
  name text not null,
  phone text not null,
  role text not null default 'Volunteer',
  ward text not null,
  organization_name text,
  verified boolean not null default false,
  blocked boolean not null default false,
  shift text not null default 'Pending Approval',
  created_at timestamptz not null default now()
);
alter table public.volunteers enable row level security;
drop policy if exists "Public volunteer registration" on public.volunteers;
create policy "Public volunteer registration" on public.volunteers for insert to anon with check (verified=false and blocked=false);
drop policy if exists "Authenticated volunteer management" on public.volunteers;
create policy "Authenticated volunteer management" on public.volunteers for all to authenticated using (true) with check (true);
grant insert on public.volunteers to anon;
grant select,insert,update,delete on public.volunteers to authenticated;
grant usage,select on sequence public.volunteers_id_seq to anon,authenticated;

create table if not exists public.site_settings (
  key text primary key,
  value jsonb not null,
  updated_at timestamptz not null default now()
);
alter table public.site_settings enable row level security;
drop policy if exists "Public read site settings" on public.site_settings;
create policy "Public read site settings" on public.site_settings for select to anon,authenticated using (true);
grant select on public.site_settings to anon;
drop policy if exists "Authenticated manage site settings" on public.site_settings;
create policy "Authenticated manage site settings" on public.site_settings for all to authenticated using (true) with check (true);
grant all on public.site_settings to authenticated;

create table if not exists public.relief_inventory (
  id bigint generated by default as identity primary key,
  camp_name text not null,
  item_name text not null,
  current_stock numeric not null default 0,
  min_required numeric not null default 0,
  unit text not null default 'Units',
  created_at timestamptz not null default now()
);
alter table public.relief_inventory enable row level security;
drop policy if exists "Authenticated manage relief inventory" on public.relief_inventory;
create policy "Authenticated manage relief inventory" on public.relief_inventory for all to authenticated using (true) with check (true);
grant all on public.relief_inventory to authenticated;
grant usage,select on sequence public.relief_inventory_id_seq to authenticated;

do $$ begin
  if not exists (select 1 from pg_publication_tables where pubname='supabase_realtime' and schemaname='public' and tablename='site_settings') then
    alter publication supabase_realtime add table public.site_settings;
  end if;
  if not exists (select 1 from pg_publication_tables where pubname='supabase_realtime' and schemaname='public' and tablename='volunteers') then
    alter publication supabase_realtime add table public.volunteers;
  end if;
  if not exists (select 1 from pg_publication_tables where pubname='supabase_realtime' and schemaname='public' and tablename='relief_inventory') then
    alter publication supabase_realtime add table public.relief_inventory;
  end if;
end $$;
